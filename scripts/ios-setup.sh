#!/bin/bash
# One command from a clean checkout to ios/IPTVPhone.xcodeproj (git-ignored; ios/project.yml is the source):
#   1. iOS libmpv (scripts/fetch-ios-mpv.sh)   2. CA bundle (scripts/make-ca-bundle.sh)
#   3. XcodeGen, pinned and hash-checked, into build/tools (never installed system-wide)   4. generate the project.
# Optional environment: IOS_TEAM_ID=<Apple Team ID> (signing team, so it survives regeneration), IPTV_BUILD=<build number> (default 1), IPTV_VERSION=<version> (default: the VERSION file).
set -euo pipefail
cd "$(dirname "$0")/.."

scripts/fetch-ios-mpv.sh
scripts/make-ca-bundle.sh

XG_VERSION=2.46.0
XG_SHA256=4d9e34b62172d645eed6457cac13fc222569974098ef4ee9c3368bedf0196806
XG_DIR="build/tools/xcodegen-$XG_VERSION"
if [ ! -x "$XG_DIR/xcodegen/bin/xcodegen" ]; then
  rm -rf "$XG_DIR"; mkdir -p "$XG_DIR"
  TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
  curl -fsSL -o "$TMP/xg.zip" "https://github.com/yonaskolb/XcodeGen/releases/download/$XG_VERSION/xcodegen.zip"
  echo "$XG_SHA256  $TMP/xg.zip" | shasum -a 256 -c -
  unzip -q "$TMP/xg.zip" -d "$XG_DIR"
fi

# Languages of the app = the folders of the shared strings (CFBundleLocalizations), plus the optional signing team.
{
  echo "# Generated by scripts/ios-setup.sh: do not edit."
  echo "targets:"
  echo "  IPTVPhone:"
  [ -n "${IOS_TEAM_ID:-}" ] && printf '    settings:\n      base:\n        DEVELOPMENT_TEAM: "%s"\n' "$IOS_TEAM_ID"
  echo "    info:"
  echo "      properties:"
  printf '        CFBundleLocalizations: [%s]\n' "$(cd Sources/IPTVMac/Resources && ls -d *.lproj | sed 's/\.lproj$//' | paste -sd, - | sed 's/,/, /g')"
} > ios/Generated/generated.yml

# IPTV_VERSION: the app version of the iPhone app when it differs from the Mac's VERSION file (App Store Connect has its own version records).
export IPTV_VERSION="${IPTV_VERSION:-$(cat VERSION)}" IPTV_BUILD="${IPTV_BUILD:-1}"
"$XG_DIR/xcodegen/bin/xcodegen" generate --spec ios/project.yml --project ios --quiet
# ios/Resources/Info-extra.plist (the resources work: launch screen, document types, local-network text...) wins over the keys of project.yml.
EXTRA=ios/Resources/Info-extra.plist
if [ -f "$EXTRA" ]; then
  python3 -I - ios/Generated/Info.plist "$EXTRA" <<'PY'
import plistlib, sys
base = plistlib.load(open(sys.argv[1], "rb")); base.update(plistlib.load(open(sys.argv[2], "rb")))
plistlib.dump(base, open(sys.argv[1], "wb"))
PY
fi
echo "ios/IPTVPhone.xcodeproj generated (version $IPTV_VERSION, build $IPTV_BUILD). Open it in Xcode, or see ios/README.md for xcodebuild."
